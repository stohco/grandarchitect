#!/usr/bin/env node
/**
 * Audit the 40-doc batch retrofit.
 * Extracts every [CANON] statement inserted by the retrofit script,
 * along with the original document title and whether the statement
 * is user-approved, derived, art-directed, procedural, or unresolved.
 *
 * Output: /home/z/my-project/retrofit-audit-report.md
 */
import { readFile, readdir, writeFile } from 'fs/promises';
import { join } from 'path';

const CORPUS_DIR = join(process.cwd(), 'corpus-extension');
const OUTPUT = join(process.cwd(), 'retrofit-audit-report.md');

async function audit() {
  const files = (await readdir(CORPUS_DIR)).filter(f => f.endsWith('.md'));
  const findings = [];

  for (const filename of files) {
    const content = await readFile(join(CORPUS_DIR, filename), 'utf-8');

    // Look for the batch-retrofit pattern: "> [CANON] <statement>" inside a
    // "Ground-Truth Annotation" section (the script's signature).
    const gtSectionMatch = content.match(/## Ground-Truth Annotation[\s\S]*?(?=\n## |\n---\n\n## |$)/);
    if (!gtSectionMatch) continue;

    const gtSection = gtSectionMatch[0];

    // Extract the [CANON] statement
    const canonMatch = gtSection.match(/>\s*\[CANON\]\s*(.+)/);
    if (!canonMatch) continue;
    const canonStatement = canonMatch[1].trim();

    // Extract the topic
    const topicMatch = gtSection.match(/\*\*Topic:\*\*\s*(.+)/);
    const topic = topicMatch ? topicMatch[1].trim() : '(unknown)';

    // Extract the truth-level header
    const tlMatch = content.match(/\*\*Truth level:\*\*\s*(.+)/);
    const truthLevel = tlMatch ? tlMatch[1].trim() : '(unknown)';

    // Determine if this was batch-inserted (has the script's signature pattern)
    const isBatchInserted = content.includes('## Ground-Truth Annotation') &&
      content.includes('> [DERIVED] All measurements in this document use SI units (doc 52). Visual concepts follow the VTP schema (doc 51). Moving entities follow MotionProfiles (doc 55).');

    if (!isBatchInserted) continue;

    // Classify the risk of the inserted [CANON] statement
    const risk = classifyRisk(canonStatement, topic);

    findings.push({
      filename,
      topic,
      truthLevel,
      canonStatement,
      risk,
      issue: risk === 'high'
        ? 'Script-generated [CANON] statement may introduce unapproved canon. Must be audited against original document and user decisions.'
        : risk === 'medium'
          ? 'Script-generated [CANON] statement is plausible but unverified. Needs claim-level review.'
          : 'Script-generated [CANON] statement appears to restate existing content. Low risk but still needs verification.',
    });
  }

  // Generate report
  const lines = [];
  lines.push('# Retrofit Audit Report');
  lines.push('');
  lines.push('**Status:** CANDIDATE — not validated. This report audits the 40-document batch retrofit commit.');
  lines.push('**Date:** ' + new Date().toISOString());
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push(`- Documents batch-retrofitted: ${findings.length}`);
  lines.push(`- High-risk inserted [CANON] statements: ${findings.filter(f => f.risk === 'high').length}`);
  lines.push(`- Medium-risk: ${findings.filter(f => f.risk === 'medium').length}`);
  lines.push(`- Low-risk: ${findings.filter(f => f.risk === 'low').length}`);
  lines.push('');
  lines.push('## Critical problem identified');
  lines.push('');
  lines.push('The batch retrofit script assigned **document-level** truth classifications, not **claim-level**.');
  lines.push('A script cannot decide that a statement is [CANON] merely because a document belongs to a topic category.');
  lines.push('Truth level belongs to individual claims, not whole documents.');
  lines.push('');
  lines.push('Every [CANON] statement below was **generated by a script** from a topic category, not extracted');
  lines.push('from user-approved decisions. These must be downgraded to [ART], [PROC], or [UNRESOLVED]');
  lines.push('unless the original document explicitly supports them.');
  lines.push('');
  lines.push('## Findings');
  lines.push('');

  for (const f of findings) {
    lines.push(`### ${f.filename}`);
    lines.push('');
    lines.push(`- **Topic:** ${f.topic}`);
    lines.push(`- **Truth level assigned:** ${f.truthLevel}`);
    lines.push(`- **Inserted [CANON] statement:**`);
    lines.push(`  > ${f.canonStatement}`);
    lines.push(`- **Risk:** ${f.risk.toUpperCase()}`);
    lines.push(`- **Issue:** ${f.issue}`);
    lines.push(`- **Required action:** Verify against original document content. If unsupported, downgrade to [DERIVED] or [UNRESOLVED].`);
    lines.push('');
  }

  lines.push('## Document-level vs claim-level annotation problem');
  lines.push('');
  lines.push('The retrofit added ONE truth-level header per document. But a single document can contain');
  lines.push('claims of different truth levels. For example, a combat document may contain:');
  lines.push('');
  lines.push('  [CANON] Cultivators can perceive spiritual energy.');
  lines.push('  [DERIVED] This requires an engine perception channel.');
  lines.push('  [ART] Spiritual perception uses restrained color separation.');
  lines.push('  [PROC] Regional presentation varies with local laws.');
  lines.push('  [UNRESOLVED] Whether mortals can perceive residual traces.');
  lines.push('');
  lines.push('Adding one header to the document does NOT classify the claims inside it.');
  lines.push('The correct approach is claim-level ground-truth records (see redesign below).');
  lines.push('');
  lines.push('## Required redesign: claim-level ground-truth records');
  lines.push('');
  lines.push('Every significant claim must have:');
  lines.push('');
  lines.push('```json');
  lines.push('{');
  lines.push('  "claimId": "stable-unique-id",');
  lines.push('  "truthLevel": "CANON | DERIVED | ART | PROC | UNRESOLVED",');
  lines.push('  "statement": "exact claim text",');
  lines.push('  "source": "doc-NN §X.Y or user-decision-YYYY-MM-DD",');
  lines.push('  "provenance": "user-approved | logically-derived | art-directed | procedural | unresolved",');
  lines.push('  "confidence": "exact | derived | art-directed | estimated",');
  lines.push('  "dependencies": ["other-claim-id", ...],');
  lines.push('  "applicableSystems": ["cultivation", "combat", ...],');
  lines.push('  "contradictions": [],');
  lines.push('  "approvalStatus": "approved | candidate | rejected | blocked"');
  lines.push('}');
  lines.push('```');
  lines.push('');
  lines.push('## Recommendation');
  lines.push('');
  lines.push('1. **Do NOT delete** the 40-doc batch retrofit yet — it is useful candidate work.');
  lines.push('2. **Mark it as [CANDIDATE]** in the worklog and in this audit report.');
  lines.push('3. **Do NOT treat it as validated ground truth** until the audit above is reviewed claim-by-claim.');
  lines.push('4. **Freeze autonomous bible claim modification** until this audit is approved.');
  lines.push('5. **Autonomous work may continue** on: engine infrastructure, validator architecture,');
  lines.push('   scheduler reliability, test infrastructure, and inspection tooling.');
  lines.push('6. **Build the claim-level ground-truth record system** to replace document-level annotation.');

  await writeFile(OUTPUT, lines.join('\n'));
  console.log(`Audit report written to ${OUTPUT}`);
  console.log(`Findings: ${findings.length} (${findings.filter(f => f.risk === 'high').length} high-risk)`);
}

function classifyRisk(canonStatement, topic) {
  const s = canonStatement.toLowerCase();
  // High risk: makes specific numerical or structural claims that a script can't verify
  if (/\d+\s*(km|m|kg|°|percent|%|x\b)/i.test(s)) return 'high';
  if (/(must|cannot|never|always|exactly|exactly one|strict)/i.test(s)) return 'high';
  // Medium risk: makes categorical claims about systems
  if (/(follows|uses|operates|requires|enforces|is deterministic)/i.test(s)) return 'medium';
  // Low risk: restates the document's existence/purpose
  return 'low';
}

audit().catch(console.error);
